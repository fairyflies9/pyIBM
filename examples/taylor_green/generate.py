"""Write the input files of the Taylor-Green example.

The Taylor-Green vortex on the doubly periodic unit box,

    u = -cos(2 pi x) sin(2 pi y) exp(-8 pi^2 nu t),
    v =  sin(2 pi x) cos(2 pi y) exp(-8 pi^2 nu t),

is an exact solution of the Navier-Stokes equations: the nonlinear term is a gradient and goes
into the pressure, so the flow just decays. Two inputs with the same physics:

    input2d        periodic_fft back end, midpoint scheme
    input2d_mac    mac back end with all four sides periodic, midpoint scheme, central advection

Both are fluid-only runs (no structure). The initial field is the initial_velocity hook in
hooks.py, so python -m pyibm run examples/taylor_green starts from the vortex; analyze.py
reads these files for the physical parameters, runs the cases and prints the decay rate and
the convergence tables.

Parameters: nu = 0.01 (rho = 1, mu = 0.01), 64 x 64 cells, dt = 2e-3, Tfinal = 0.5
(the amplitude decays to exp(-8 pi^2 0.01 0.5) = 0.674), output every 25 steps.
Run from anywhere: python examples/taylor_green/generate.py (main(out_dir) writes the same
files into another folder; the tests compare them with the committed ones byte for byte).
"""

from __future__ import annotations

import os
import sys

# Let the script run from a plain clone (no pip install -e .).
_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from pyibm.inputfile import (BCParams, FluidParams, GridParams, OutputParams, Parameters,
                             SolverParams, StructureParams, TimeParams, write_input_file)

HERE = os.path.dirname(os.path.abspath(__file__))

RHO = 1.0          # kg/m^2
MU = 0.01          # N s/m^2, so nu = 0.01 m^2/s
L = 1.0            # m, box side (Lx = Ly)
N = 64             # cells per side of the default run
DT = 2e-3          # s
TFINAL = 0.5       # s
PRINT_DUMP = 25


def parameters(backend: str) -> Parameters:
    """The default run on one back end. Fluid only; all sides periodic."""
    solver = SolverParams(backend=backend, time_scheme="midpoint", advection="central")
    return Parameters(
        fluid=FluidParams(rho=RHO, mu=MU),
        time=TimeParams(Tfinal=TFINAL, dt=DT),
        grid=GridParams(Nx=N, Ny=N, Lx=L, Ly=L),
        solver=solver,
        bc=BCParams(),
        structure=StructureParams(),
        output=OutputParams(print_dump=PRINT_DUMP, save_vtk=True, save_history=True, plot=False,
                            output_dir="viz/" + backend),
    )


FILES = ("input2d", "input2d_mac")


def main(out_dir: str = HERE) -> list[str]:
    written = []
    for fname, backend in zip(FILES, ("periodic_fft", "mac")):
        header = (f"Taylor-Green vortex on the doubly periodic unit box, {backend} back end\n"
                  "u = -cos(2 pi x) sin(2 pi y) exp(-8 pi^2 nu t), v = sin(2 pi x) cos(2 pi y) exp(-8 pi^2 nu t)\n"
                  "fluid only; the initial field is the initial_velocity hook in hooks.py\n"
                  "generated by generate.py, do not edit by hand")
        path = os.path.join(out_dir, fname)
        write_input_file(path, parameters(backend), header=header)
        written.append(path)
        print("wrote", os.path.relpath(path, out_dir))
    return written


if __name__ == "__main__":
    main()
