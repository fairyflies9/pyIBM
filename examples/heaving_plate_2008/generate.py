"""Write the structure and input files of the 2008 heaving-plate case.

The plate is 16 target points on a vertical line at x = 0.2, y = 0.1 + i*0.0125
(i = 0..15), i.e. half the box tall and spaced ds = dx/2, in a 0.4 x 0.4 periodic box of
16 x 16 cells with mu = 3, rho = 2. The time step is dt = dx^2/nu = 0.025^2/1.5 evaluated
in floating point exactly as the MATLAB code evaluates it, so the regression test
(tests/test_matlab_regression.py) steps on the same times. Tfinal is 100 steps.

Three inputs:

    input2d             stiffness 1 (the 2008 value), pm1996, cosine4
    input2d_stiff1e4    stiffness 1e4, pm1996, cosine4 (the regression reference)
    input2d_midpoint    stiffness 1e4, midpoint, peskin4 (the setup we recommend in pyIBM)

Two structures because the stiffness lives in the .target file: plate (k = 1) and
plate_stiff1e4 (k = 1e4). Run from anywhere: python examples/heaving_plate_2008/generate.py
(main(out_dir) writes the same files into another folder; the tests compare them with the
committed ones byte for byte).
"""

from __future__ import annotations

import os
import sys

# Let the script run from a plain clone (no pip install -e .).
_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

import numpy as np

from pyibm.inputfile import (BCParams, FluidParams, GridParams, OutputParams, Parameters,
                             SolverParams, StructureParams, TimeParams, write_input_file)
from pyibm.structures import Structure, Targets, write_structure

HERE = os.path.dirname(os.path.abspath(__file__))

N_POINTS = 16
X_PLATE = 0.2          # m, the plate's rest position in x (half the box width)
Y_BOTTOM = 0.1         # m, a quarter of the box height
DS = 0.0125            # m, point spacing = dx/2
NX = NY = 16
LX = LY = 0.4          # m
MU = 3.0               # N s/m^2
RHO = 2.0              # kg/m^2
DX = LX / NX           # 0.025 m
NU = MU / RHO          # 1.5 m^2/s
DT = 0.025 * 0.025 / 1.5   # = dx^2/nu as MATLAB evaluates it: 4.1666666666666675e-4
N_STEPS = 100


def plate_points() -> np.ndarray:
    i = np.arange(N_POINTS)
    return np.column_stack([np.full(N_POINTS, X_PLATE), Y_BOTTOM + i * DS])


def write_plate(name: str, stiffness: float, out_dir: str = HERE) -> list[str]:
    X = plate_points()
    s = Structure(name=name, X=X, ds=np.full(N_POINTS, DS),
                  targets=Targets(np.arange(N_POINTS), np.full(N_POINTS, stiffness), X))
    return write_structure(out_dir, s)


def parameters(name: str, time_scheme: str, kernel: str, output_dir: str) -> Parameters:
    return Parameters(
        fluid=FluidParams(rho=RHO, mu=MU),
        time=TimeParams(Tfinal=N_STEPS * DT, dt=DT),
        grid=GridParams(Nx=NX, Ny=NY, Lx=LX, Ly=LY),
        solver=SolverParams(backend="periodic_fft", time_scheme=time_scheme, coupling="delta",
                            kernel=kernel),
        bc=BCParams(),
        structure=StructureParams(name=name, ds=DS),
        output=OutputParams(print_dump=5, save_vtk=True, save_history=True, plot=False,
                            output_dir=output_dir),
    )


def main(out_dir: str = HERE) -> list[str]:
    """Write the structure and input files into out_dir (default: this directory)."""
    written = write_plate("plate", 1.0, out_dir) + write_plate("plate_stiff1e4", 1e4, out_dir)
    cases = [
        ("input2d", "plate", "pm1996", "cosine4", "viz/stiff1",
         "stiffness 1, Peskin & McQueen 1996 scheme, cosine kernel: the 2008 settings"),
        ("input2d_stiff1e4", "plate_stiff1e4", "pm1996", "cosine4", "viz/stiff1e4",
         "stiffness 1e4, same scheme and kernel: the regression reference"),
        ("input2d_midpoint", "plate_stiff1e4", "midpoint", "peskin4", "viz/midpoint",
         "stiffness 1e4, midpoint scheme, 4-point kernel: the second-order run"),
    ]
    for fname, name, scheme, kernel, out, what in cases:
        header = (f"heaving plate, 2008 MATLAB case: {what}\n"
                  f"dt = dx^2/nu = 0.025^2/1.5 = {DT!r}; Tfinal = {N_STEPS} steps\n"
                  "generated by generate.py, do not edit by hand")
        path = os.path.join(out_dir, fname)
        write_input_file(path, parameters(name, scheme, kernel, out), header=header)
        written.append(path)
    for p in written:
        print("wrote", os.path.relpath(p, out_dir))
    return written


if __name__ == "__main__":
    main()
