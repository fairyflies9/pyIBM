"""Write the input files of Stokes' second problem (no structure: a fluid-only case).

The bottom wall of a box slides as u = U cos(omega t) (hooks.py); the top wall is at rest
ten penetration depths away; the sides are periodic, so the problem is one-dimensional and
Nx = 8 cells (the smallest the grid allows) are enough. The physical constants live in
stokes_exact.py. Three inputs differ only in the vertical resolution:

    input2d          Ny = 64    (6.4 cells per penetration depth d)
    input2d_ny32     Ny = 32    (3.2 cells per d)
    input2d_ny128    Ny = 128   (12.8 cells per d)

The cells are square (Lx = Nx dy), the time step is T/400 and the run is five periods with
output every T/8, so analyze.py can compare eight phases of the last period with the exact
solution. Run from anywhere: python examples/stokes_second_problem/generate.py
"""

from __future__ import annotations

import os
import sys

# Let the script run from a plain clone (no pip install -e .).
_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)
HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import stokes_exact as ex
from pyibm.inputfile import (BCParams, FluidParams, GridParams, OutputParams, Parameters,
                             SolverParams, StructureParams, TimeParams, write_input_file)

NX = 8                          # cells along the periodic direction
STEPS_PER_PERIOD = 400
DT = ex.PERIOD / STEPS_PER_PERIOD
PERIODS = 5
PRINT_DUMP = STEPS_PER_PERIOD // 8      # output every T/8: eight phases per period

VARIANTS = (
    ("input2d", 64, "viz/ny64"),
    ("input2d_ny32", 32, "viz/ny32"),
    ("input2d_ny128", 128, "viz/ny128"),
)


def parameters(Ny: int, output_dir: str) -> Parameters:
    dy = ex.LY / Ny
    return Parameters(
        fluid=FluidParams(rho=ex.RHO, mu=ex.RHO * ex.NU),
        time=TimeParams(Tfinal=PERIODS * ex.PERIOD, dt=DT),
        grid=GridParams(Nx=NX, Ny=Ny, Lx=NX * dy, Ly=ex.LY),
        solver=SolverParams(backend="mac", time_scheme="midpoint", coupling="delta",
                            kernel="peskin4", advection="blend", viscous="implicit"),
        bc=BCParams(left="periodic", right="periodic", bottom="dirichlet", top="dirichlet"),
        structure=StructureParams(),
        output=OutputParams(print_dump=PRINT_DUMP, save_vtk=True, save_history=True, plot=False,
                            output_dir=output_dir),
    )


def main(out_dir: str = HERE) -> list[str]:
    """Write the three inputs into out_dir (default: this directory); return their paths."""
    written = []
    for fname, Ny, out in VARIANTS:
        header = (f"Stokes' second problem: bottom wall u = U cos(omega t), U = {ex.U:g} m/s, "
                  f"omega = 2 pi rad/s, nu = {ex.NU!r} m^2/s (penetration depth d = {ex.D:g} m)\n"
                  f"Ny = {Ny} ({Ny * ex.D / ex.LY:g} cells per d), dt = T/{STEPS_PER_PERIOD}, "
                  f"{PERIODS} periods, output every T/{STEPS_PER_PERIOD // PRINT_DUMP}\n"
                  "generated by generate.py, do not edit by hand")
        path = os.path.join(out_dir, fname)
        write_input_file(path, parameters(Ny, out), header=header)
        written.append(path)
        print("wrote", os.path.relpath(path, out_dir))
    return written


if __name__ == "__main__":
    main()
