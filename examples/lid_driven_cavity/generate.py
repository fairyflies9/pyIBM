"""Write the input files of the lid-driven cavity example.

The unit square with no-slip walls and a lid sliding in +x at U = 1 (hooks.py), rho = 1,
mu = 1/Re, MAC back end, midpoint scheme, central advection, implicit viscosity. Three steady
cases compared with Tables I and II of Ghia, Ghia & Shin 1982 (ghia1982.py):

    input2d          Re = 100,   64 x 64,  Tfinal = 18
    input2d_re400    Re = 400,  128 x 128, Tfinal = 40
    input2d_re1000   Re = 1000, 128 x 128, Tfinal = 70   (slow test only)

Tfinal is chosen so that the relative change of the kinetic energy, |dKE/dt|/KE, is below
1e-4 per second at the end (the transient decays at about 0.55/s at Re 100, 0.26/s at
Re 400 and 0.11/s at Re 1000; analyze.py prints the end value).

There is also a demonstration with the lid speed U(t) = sin(2 pi t). Its Hooks section names
its own hooks file, hooks_oscillating.py, so it shares this directory with the steady cases:

    input2d_oscillating   Re = 100, 128 x 128, four periods, history every 8 steps, no VTK

The time step is dt = CFL h / U with CFL = 0.4, which keeps the solver's CFL bound
dt (max|u|/dx + max|v|/dy) near 0.6. Run from anywhere: python examples/lid_driven_cavity/generate.py
(main(out_dir) writes the same files into another folder; the tests compare them with the
committed ones byte for byte).
"""

from __future__ import annotations

import os
import sys

# Let the script run from a plain clone (no pip install -e .).
_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from pyibm.inputfile import (BCParams, FluidParams, GridParams, HooksParams, OutputParams,
                             Parameters, SolverParams, StructureParams, TimeParams,
                             write_input_file)

HERE = os.path.dirname(os.path.abspath(__file__))

RHO = 1.0        # kg/m^2
L = 1.0          # m, cavity side
U_LID = 1.0      # m/s, must match hooks.U_LID
CFL = 0.4        # dt = CFL * h / U_LID

# input name, Re, cells per side, Tfinal [s], steps between outputs, output directory
STEADY = (
    ("input2d", 100, 64, 18.0, 80, "viz/re100"),
    ("input2d_re400", 400, 128, 40.0, 640, "viz/re400"),
    ("input2d_re1000", 1000, 128, 70.0, 1120, "viz/re1000"),
)

# the oscillating lid: Re (on U_LID), cells per side, number of periods of 1 s, steps between outputs
OSCILLATING = (100, 128, 4, 8)
OSC_PERIOD = 1.0   # s, must match hooks_oscillating.PERIOD
OSC_INPUT = "input2d_oscillating"
OSC_HOOKS = "hooks_oscillating.py"
OSC_OUTPUT = "viz/oscillating"


def time_step(N: int) -> float:
    return CFL * (L / N) / U_LID


def parameters(Re: float, N: int, Tfinal: float, print_dump: int, output_dir: str,
               save_vtk: bool = True, hooks_file: str = "hooks.py") -> Parameters:
    return Parameters(
        fluid=FluidParams(rho=RHO, mu=RHO * U_LID * L / Re),
        time=TimeParams(Tfinal=Tfinal, dt=time_step(N)),
        grid=GridParams(Nx=N, Ny=N, Lx=L, Ly=L),
        solver=SolverParams(backend="mac", time_scheme="midpoint", advection="central",
                            viscous="implicit"),
        bc=BCParams(left="dirichlet", right="dirichlet", bottom="dirichlet", top="dirichlet"),
        structure=StructureParams(),
        output=OutputParams(print_dump=print_dump, save_vtk=save_vtk, save_history=True,
                            plot=False, output_dir=output_dir),
        hooks=HooksParams(file=hooks_file),
    )


def steady_parameters(input_name: str) -> Parameters:
    for name, Re, N, Tfinal, dump, out in STEADY:
        if name == input_name:
            return parameters(Re, N, Tfinal, dump, out)
    raise KeyError(input_name)


def oscillating_parameters() -> Parameters:
    Re, N, periods, dump = OSCILLATING
    return parameters(Re, N, periods * OSC_PERIOD, dump, OSC_OUTPUT, save_vtk=False,
                      hooks_file=OSC_HOOKS)


FILES = tuple(name for name, *_ in STEADY) + (OSC_INPUT,)


def main(out_dir: str = HERE) -> list[str]:
    written = []
    for name, Re, N, Tfinal, dump, out in STEADY:
        header = (f"lid-driven cavity, Re = {Re}, {N} x {N}, lid U = {U_LID:g} in +x (hooks.py)\n"
                  f"dt = {CFL:g} h / U = {time_step(N)!r}; compared with Ghia, Ghia & Shin 1982 Tables I and II\n"
                  "generated by generate.py, do not edit by hand")
        path = os.path.join(out_dir, name)
        write_input_file(path, parameters(Re, N, Tfinal, dump, out), header=header)
        written.append(path)
    Re, N, periods, dump = OSCILLATING
    header = (f"lid-driven cavity with an oscillating lid U(t) = {U_LID:g} sin(2 pi t/{OSC_PERIOD:g}) "
              f"({OSC_HOOKS}), Re = {Re} on the peak lid speed, {N} x {N}, {periods} periods\n"
              f"dt = {CFL:g} h / U = {time_step(N)!r}; a demonstration, no reference\n"
              "generated by generate.py, do not edit by hand")
    path = os.path.join(out_dir, OSC_INPUT)
    write_input_file(path, oscillating_parameters(), header=header)
    written.append(path)
    for path in written:
        print("wrote", os.path.relpath(path, out_dir))
    return written


if __name__ == "__main__":
    main()
